def pick_engine(topic: str | None, rng: random.Random | None = None) -> Framework:
    """Форма сюжета: «Учимся жизни» — всегда про страх, иначе случайная из 22 (поиск и пропажи только в трёх)."""
    if topic == "life_lesson":
        return FEAR
    return (rng or random.SystemRandom()).choice(ENGINES)


