"""Формат книги в одном месте: размеры картинок, на какой половине разворота лежит текст.

Обложка квадратная (1024×1024). Каждая из страниц истории — ОДНА широкая иллюстрация на весь разворот
(2:1, 2048×1024); текст лежит поверх неё: у нечётных страниц на ПРАВОЙ половине, у чётных на ЛЕВОЙ.
Картинки просят у модели так, чтобы герои были на другой половине, а половина под текст была спокойной.
"""
from __future__ import annotations

COVER_SIZE = (1024, 1024)           # обложка: квадрат с названием внутри картинки
PAGE_SIZE = (2048, 1024)            # страница истории: широкий разворот 2:1 (ширина и высота кратны 16)
COVER_QUALITY = 90                  # качество JPEG обложки
PAGE_QUALITY = 88                   # качество JPEG страниц истории


def size_str(size: tuple[int, int]) -> str:
    """(2048, 1024) -> '2048x1024': так размер просят у провайдера картинок."""
    return f"{size[0]}x{size[1]}"


def parse_size(text: str) -> tuple[int, int]:
    """'2048x1024' -> (2048, 1024)."""
    w, _, h = str(text).lower().partition("x")
    return int(w), int(h)


def text_side(number: int) -> str:
    """Где лежит текст страницы number (с 1): нечётные — справа, чётные — слева."""
    return "right" if number % 2 == 1 else "left"


def calm_side(number: int) -> str:
    """Половина картинки, которая остаётся спокойной и свободной под текст (то же, что сторона текста)."""
    return text_side(number)


def hero_side(number: int) -> str:
    """Половина, где стоят герои: противоположная той, где лежит текст."""
    return "left" if text_side(number) == "right" else "right"
