def build_system_prompt(profile: Profile) -> str:
    """Системная инструкция автора. Лимиты стоят в начале и в конце; план и анкета приходят в сообщении пользователя."""
    text = (AUTHOR_TEMPLATE
            .replace("{pages}", str(PAGES))
            .replace("{language}", _language_name(profile))
            .replace("{age}", _age_text(profile))
            .replace("{gender}", _gender_text(profile))
            .replace("{limits}", limits_text(profile))
            .replace("{magic}", MAGIC_ISLAMIC if profile.islamic else MAGIC_OK)
            .replace("{reference}", reference_text(profile))
            .replace("{name_max}", str(D.NAME_MAX_USES))
            .replace("{safety}", SAFETY)
            .replace("{data_note}", DATA_NOTE))
    parts = [text.rstrip()]
    if profile.language == "ky":
        parts.append(KY_AUTHOR_NOTE
                     .replace("{intensifiers}", ", ".join(D.KY_INTENSIFIERS))
                     .replace("{idiophones}", ", ".join(D.KY_IDIOPHONES))
                     .replace("{proverb}", D.KY_PROVERBS[0].rstrip(".")))
    parts.append(examples_text(profile))
    parts.append(f"Формы имени героя «{first_name(profile.name)}» (бери отсюда): "
                 + forms_table(profile.name, profile.gender, profile.language))
    if profile.islamic:
        parts.append(text_rules_of_islamic_block())
    parts.append(f"Схема JSON (в pages ровно {PAGES} элементов):\n" + AUTHOR_SCHEMA.replace("{pages}", str(PAGES)))
