def years(age: int) -> str:
    if age == 1:
        return "год"
    return "года" if 2 <= age <= 4 else "лет"


def _age_text(profile: Profile) -> str:
    return f"{profile.age} {years(profile.age)}"


def _language_name(profile: Profile) -> str:
    return options.LANGUAGES[profile.language]["name_in_prompt"]


def _child_json(profile: Profile) -> str:
    return json.dumps(profile.for_model(), ensure_ascii=False, indent=2)


_UP_TO_SENTENCES = {1: "одного предложения", 2: "двух предложений", 3: "трёх предложений", 4: "четырёх предложений"}


def sentences_limit(n: int) -> str:
    """«не больше двух предложений»: число в родительном падеже словами."""
    return _UP_TO_SENTENCES.get(n, f"{n} предложений")


def limits_core(profile: Profile) -> str:
    lim = page_limits(profile.age, profile.language)
    return (f"от {lim.min_words} до {lim.max_words} слов, не больше {lim.max_chars} знаков, "
            f"не больше {sentences_limit(lim.max_sentences)}, в одном предложении не больше {lim.max_sentence_words} слов")


def limits_text(profile: Profile) -> str:
    language = "кыргызский" if profile.language == "ky" else "русский"
    return (f"Лимиты текста на ОДНУ страницу (ребёнку {_age_text(profile)}, язык книги: {language}): {limits_core(profile)}. "
            f"Название — не больше {D.TITLE_MAX_WORDS} слов. Имя героя — не больше {D.NAME_MAX_USES} раз на все {PAGES} страниц. "
            f"Строка moral — не больше {D.MORAL_MAX_WORDS} слов. Программа считает слова и знаки сама: "
            "страницу, которая не уложилась, вернут тебе на переписывание.")


def _gender_text(profile: Profile) -> str:
    if profile.language == "ky":
        return f"Герой — {profile.gender_word}."
    form = "женском" if profile.gender == "girl" else "мужском"
    return f"Герой — {profile.gender_word}: глаголы прошедшего времени про героя стоят в {form} роде."


